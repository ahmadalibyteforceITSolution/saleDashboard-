import mongoose from 'mongoose'

const workshopJobCardSchema = new mongoose.Schema({
  id: { type: String, unique: true, sparse: true },
  jobCardNo: { type: String, unique: true, sparse: true },
  date: { type: String },
  receivingDate: { type: String },
  expectedDeliveryDate: { type: String },
  completedDate: { type: String },
  customerName: { type: String, required: true },
  customerCode: { type: String },
  customerContact: { type: String },
  customerType: { type: String, default: 'Existing Company Customer' },
  machineName: { type: String, default: 'Medical Equipment' },
  brand: { type: String },
  model: { type: String },
  serialCode: { type: String },
  machineCode: { type: String },
  productCode: { type: String },
  warrantyStatus: { type: String, default: 'Out of Warranty' },
  isWarranty: { type: Boolean, default: false },
  customerComplaint: { type: String },
  machineCondition: { type: String },
  accessoriesReceived: { type: String },
  assignedTechnician: { type: String },
  status: { type: String, default: 'Received' },
  reportedFault: { type: String },
  diagnosis: { type: String },
  requiredRepair: { type: String },
  technicianRemarks: { type: String },
  partsUsed: { type: Array, default: [] },
  partsTotal: { type: Number, default: 0 },
  labourCharges: { type: Number, default: 0 },
  serviceCharges: { type: Number, default: 0 },
  otherCharges: { type: Number, default: 0 },
  discount: { type: Number, default: 0 },
  taxRate: { type: Number, default: 0 },
  taxAmount: { type: Number, default: 0 },
  grandTotal: { type: Number, default: 0 },
  paidAmount: { type: Number, default: 0 },
  balanceDue: { type: Number, default: 0 },
  paymentStatus: { type: String, default: 'Unpaid' },
  invoiceNo: { type: String },
  dcNo: { type: String },
  deliveryCharges: { type: Number, default: 0 },
  cargoService: { type: String, default: '' },
  shipmentType: { type: String, default: 'Cargo' },
  trackingNo: { type: String, default: '' },
  dispatchDate: { type: String },
  dispatchedBy: { type: String },
  receiverName: { type: String },
  receiverPhone: { type: String },
  deliveryAddress: { type: String },
  dispatchStatus: { type: String, default: 'Pending' },
  repairedBy: { type: String },
  repairCompletedDate: { type: String },
  payments: { type: Array, default: [] },
  history: { type: Array, default: [] }
}, { timestamps: true, strict: false })

export default mongoose.model('WorkshopJobCard', workshopJobCardSchema)
